    entities = [
        TaskEntity::class,
        TimeEntryEntity::class,
        NoteEntity::class,
        TaskOccurrenceEntity::class,
        TaskRescheduleEntity::class,
        DayJournalEntryEntity::class,
        DayJournalResponseEntity::class,
