const val PAYANAM_DATABASE_SCHEMA_VERSION = 21

/**
 * Room Database for Payanam.
 *
 * Schema version 17 - Habit recurrence system overhaul (uHabits-aligned).
 * - Removed task_occurrences.autoGenerated column (absence = implicitly missed)
 * - Removed tasks.recurrenceStrategy and tasks.dayBoundaryHour columns
 * - Converted all recurrenceRule values from CONFIG:/RRULE: to "num/den" format
 *
 * Schema version 16 - Day plan policy contract hardening.
 * - Added day_plan_policies table for per-day mode/template/starred policy
 * - Added day_type_template_preferences table for auto-template mappings
 *
 * Schema version 15 - Phase 7: Journal + Notes consolidation.
 * - Added journal_notes table for multi-entry freeform notes per day/dimension
 * - Migrated legacy notes rows into journal_notes
 *
 * Schema version 14 - Phase 6: Day Planning + Scoring.
 * - Added day_plan_templates table for reusable day plan presets
 * - Added day_plan_template_allocations table for template dimension entries
 * - Added day_plan_allocations table for per-day planned minutes per dimension
 *
 * Schema version 13 - Phase 4.5: Planning & Reality Lens.
 * - Added lens_reflections table for gap detection and reflection cards
 *
 * Schema version 12 - Phase-3 time parity foundation (tags/goals/rules).
 * - Added tags table + task/note/time_entry tag mapping tables
 * - Added time_goals and time_rules tables
 *
 * Schema version 11 - Recurring occurrence reason persistence.
 * - Added task_occurrences.statusReason to persist structured reason values.
 *
 * Schema version 10 - Day-key query foundation + insights cache.
 * - Added day_key columns to tasks/time_entries/notes with indexes
 * - Added daily_insights cache table
 *
 * Schema version 9 - Import metadata foundation.
 * - Added import_batches table
 * - Added import_source/import_id/imported_at/import_batch_id on tasks and time_entries
 *
 * Schema version 8 - Dimension foundation.
 * - Added life_dimensions table + Unassigned seed row
 * - Added user_preferences typed settings table
 * - Added dimension_id columns to tasks/time_entries/notes/day_journal_responses
 *
 * Schema version 7 - Focus tracking fields for time entries.
 * - Added focusRating, focusNote, focusRatedAt to time_entries
 *
 * Schema version 6 - Actual completion tracking.
 * - Added actualCompletedAt, actualDurationMinutes to task_occurrences
 *
 * Schema version 5 - Recurrence redesign with decay scoring.
 * - Added currentScore, lastOccurrenceDate, dayBoundaryHour to tasks
 * - Added autoGenerated to task_occurrences
 *
 * Note: When migrating from the Capacitor version, we'll need to handle
 * the existing SQLite database files. Room can open existing databases
 * if the schema matches.
 */
